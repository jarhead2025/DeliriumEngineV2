int BitmapFont::Measure(const std::string& text, int scale) {
    return static_cast<int>(text.size()) * kAdvance * scale;
}

std::string BitmapFont::Ellipsize(const std::string& text, int max_px, int scale) {
    if (max_px <= 0) return {};
    const int per = kAdvance * scale;
    const int max_chars = max_px / per;
    if (max_chars <= 0) return {};
    if (static_cast<int>(text.size()) <= max_chars) return text;
    if (max_chars <= 3) return text.substr(0, size_t(max_chars));
    return text.substr(0, size_t(max_chars - 3)) + "...";
}

